// let keyword
let firstName = "Kevin";
let lastName = "Rosengren";
console.log(firstName + lastName);

// Reassign variable to a different value
firstName = "El Jefe";
console.log(firstName);

// const keyword
const age = 123;
console.log(age);

// const keyword cannot be reassigned (script.js:15 Uncaught TypeError: Assignment to constant variable.)
age = 456;
